# for :- for loop ka use kisi sequence (list, string, range, etc.) ke har element par iterate karne ke liye hota hai.

# Example 1
for i in range(5):
    print(i)

# Example 2
for i in range(1, 6):
    print(i)

# Example 3
for i in range(0, 11, 2):
    print(i)
